export function getSafeExercisesForMuscle(
  muscle: "chest" | "back" | "legs" | "shoulders" | "arms" | "core",
  injuries: string[] = []
): Exercise[] {
  return exercisesDatabase.filter((ex) => {
    if (ex.muscleGroup !== muscle) return false;
    const hasInjuryRisk = ex.injuryRisks.some((risk) => injuries.includes(risk));
    return !hasInjuryRisk;
  });
}

export function getExerciseById(id: string): Exercise | undefined {
  return exercisesDatabase.find((e) => e.id === id);
}

